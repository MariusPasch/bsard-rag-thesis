"""Render thesis-grade cross-arm tables from the consolidated long dataframe.

Inputs are the long df produced by :mod:`arm_results.consolidate` (one row per
stem × method × metric). No metric computation here — only selection, pivoting,
and averaging of values T07 already produced.

Outputs (under data/tables/):
  cross_arm_headline.csv / .md   — macro (per-PDF mean) + micro (question-weighted)
                                    R@10 / R@100 / MRR@10 / nDCG@10 per method
  cross_arm_per_stem.md          — the same headline metrics, one block per PDF
  cross_arm_full.csv             — every raw T07 metric key, stem × method wide
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

# display name → ordered candidate T07 metric keys (first present wins)
HEADLINE_METRICS: list[tuple[str, list[str]]] = [
    ("R@10", ["T1/R@10", "T2/P1/Recall@10"]),
    ("R@100", ["T1/R@100", "T2/P1/Recall@100"]),
    ("MRR@10", ["T2/P2/MRR@10"]),
    ("nDCG@10", ["T2/P2/NDCG@10"]),
]


# ---------------------------------------------------------------------------
# helpers
# ---------------------------------------------------------------------------

def _resolve_headline(long_df: pd.DataFrame) -> pd.DataFrame:
    """Wide frame: stem, stem_label, method, n_gt_q + one col per headline metric."""
    wide = long_df.pivot_table(
        index=["stem", "stem_label", "method", "n_gt_q"],
        columns="metric",
        values="value",
        aggfunc="first",
    ).reset_index()

    out_cols = {}
    for display, candidates in HEADLINE_METRICS:
        col = next((c for c in candidates if c in wide.columns), None)
        out_cols[display] = wide[col] if col is not None else pd.NA

    base = wide[["stem", "stem_label", "method", "n_gt_q"]].copy()
    for display, series in out_cols.items():
        base[display] = series
    return base


def _macro_micro(headline: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Aggregate per-method across PDFs: macro (mean of PDFs) and micro (q-weighted)."""
    metric_cols = [d for d, _ in HEADLINE_METRICS]

    macro = (
        headline.groupby("method")[metric_cols]
        .mean(numeric_only=True)
        .reset_index()
    )
    macro["n_pdfs"] = headline.groupby("method")["stem"].count().values

    def _wmean(g: pd.DataFrame) -> pd.Series:
        w = g["n_gt_q"].astype(float)
        return pd.Series(
            {m: (g[m] * w).sum() / w.sum() if w.sum() else float("nan")
             for m in metric_cols}
        )

    micro = headline.groupby("method").apply(_wmean).reset_index()
    micro["n_q_total"] = headline.groupby("method")["n_gt_q"].sum().values

    macro = macro.sort_values("R@10", ascending=False).round(4)
    micro = micro.sort_values("R@10", ascending=False).round(4)
    return macro, micro


def _df_to_md(df: pd.DataFrame) -> str:
    """Minimal GitHub-flavoured markdown table (avoids a tabulate dependency)."""
    cols = list(df.columns)
    head = "| " + " | ".join(str(c) for c in cols) + " |"
    sep = "| " + " | ".join("---" for _ in cols) + " |"
    lines = [head, sep]
    for _, row in df.iterrows():
        cells = []
        for c in cols:
            v = row[c]
            if isinstance(v, float):
                cells.append(f"{v:.4f}")
            else:
                cells.append("" if pd.isna(v) else str(v))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# emitters
# ---------------------------------------------------------------------------

def emit_headline(long_df: pd.DataFrame, out_dir: Path) -> pd.DataFrame:
    headline = _resolve_headline(long_df)
    macro, micro = _macro_micro(headline)

    macro.to_csv(out_dir / "cross_arm_headline.csv", index=False)
    md = [
        "# Cross-arm headline metrics",
        "",
        "All arms scored through one path (T07 `evaluation.comparator.evaluate`, "
        "tiers 1+2) against the per-PDF curated GT (`runs/t04_<stem>.json`). "
        "Generated by `arm_results.consolidate`.",
        "",
        "## Macro average (unweighted mean across the 5 PDFs)",
        "",
        _df_to_md(macro),
        "",
        "## Micro average (weighted by question count per PDF)",
        "",
        _df_to_md(micro),
        "",
        "> Caveat: retrieval pool depths differ (T03=200, T04=100, T05=100); "
        "R@100 structurally favours T03's deeper pool. T0 latency is not "
        "cross-comparable (only T05 recorded per-query latency).",
        "",
    ]
    (out_dir / "cross_arm_headline.md").write_text("\n".join(md), encoding="utf-8")
    return macro


def emit_per_stem(long_df: pd.DataFrame, out_dir: Path) -> None:
    headline = _resolve_headline(long_df)
    metric_cols = [d for d, _ in HEADLINE_METRICS]
    blocks = ["# Cross-arm metrics per PDF", ""]
    for stem, g in headline.groupby("stem"):
        label = g["stem_label"].iloc[0]
        n_gt = int(g["n_gt_q"].iloc[0])
        tbl = g[["method", *metric_cols]].sort_values("R@10", ascending=False)
        blocks += [f"## {label}  (`{stem}`, {n_gt} questions)", "",
                   _df_to_md(tbl.round(4)), ""]
    (out_dir / "cross_arm_per_stem.md").write_text("\n".join(blocks), encoding="utf-8")


def emit_full(long_df: pd.DataFrame, out_dir: Path) -> None:
    full = long_df.pivot_table(
        index=["stem", "stem_label", "method"],
        columns="metric",
        values="value",
        aggfunc="first",
    ).reset_index()
    full.to_csv(out_dir / "cross_arm_full.csv", index=False)


def emit_extended(long_df: pd.DataFrame, out_dir: Path) -> None:
    """Write an E/ (effective, drift-aware) + W/ (weighted) summary when present.

    Macro mean across PDFs, shown next to T1/R@10 for reference. E/ is computed
    only over evaluable questions (GT present in the PDF); W/ applies to the
    chunk-based T03 arm only.
    """
    metrics_present = set(long_df["metric"].unique())
    e_keys = [k for k in ("E/recall@10", "E/recall@100") if k in metrics_present]
    w_keys = [k for k in ("W/recall@10", "W/recall@100") if k in metrics_present]
    if not e_keys and not w_keys:
        return

    wide = long_df.pivot_table(
        index="method", columns="metric", values="value", aggfunc="mean"
    ).reset_index()
    blocks = ["# Extended metrics (macro mean across PDFs)", ""]

    if e_keys:
        cols = ["method"] + [k for k in ("T1/R@10", *e_keys) if k in wide.columns]
        tbl = wide[cols].sort_values(e_keys[0], ascending=False).round(4)
        blocks += [
            "## Effective / drift-aware recall (E/)",
            "",
            "Recall denominator restricted to GT articles locatable in the PDF "
            "(`gt_in_pdf`); not-evaluable questions excluded. `T1/R@10` shown for reference.",
            "",
            _df_to_md(tbl),
            "",
        ]

    if w_keys:
        cols = ["method"] + [k for k in w_keys if k in wide.columns]
        tbl = wide[cols].dropna(subset=w_keys, how="all").round(4)
        blocks += [
            "## Weighted partial-relevance recall (W/, chunk-based arms only)",
            "",
            "Per-article credit = capped sum of overlapping-chunk weights "
            "(applies to T03; article-level arms have no W/). Uses a chunk-level "
            "cutoff (top-k chunks), so it is comparable to — not identical with — "
            "binary article-level R@k.",
            "",
            _df_to_md(tbl),
            "",
        ]

    (out_dir / "cross_arm_extended.md").write_text("\n".join(blocks), encoding="utf-8")


def emit_all(long_df: pd.DataFrame, out_dir: Path) -> pd.DataFrame:
    macro = emit_headline(long_df, out_dir)
    emit_per_stem(long_df, out_dir)
    emit_full(long_df, out_dir)
    emit_extended(long_df, out_dir)
    return macro
